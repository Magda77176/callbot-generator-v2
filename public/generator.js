#!/usr/bin/env node

/**
 * CallBot Generator V2 - Template Driven
 */

const fs = require('fs-extra');
const path = require('path');
const inquirer = require('inquirer');
const PromptGenerator = require('./core/prompt-generator');
const FlowEngine = require('./core/flow-engine');
const ContextEnricher = require('./core/context-enricher');

class CallBotGenerator {
  constructor() {
    this.promptGenerator = new PromptGenerator();
    this.contextEnricher = new ContextEnricher();
    this.templatesDir = path.join(__dirname, 'templates');
    this.outputDir = path.join(__dirname, 'generated');
  }

  async init() {
    await fs.ensureDir(this.outputDir);
  }

  // Liste tous les templates disponibles
  async listTemplates() {
    const templateFiles = await fs.readdir(this.templatesDir);
    const templates = [];
    
    for (const file of templateFiles) {
      if (file.endsWith('.json')) {
        const templatePath = path.join(this.templatesDir, file);
        const template = await fs.readJson(templatePath);
        templates.push({
          id: template.metadata.id,
          name: template.metadata.name,
          description: template.metadata.description,
          file: file
        });
      }
    }
    
    return templates;
  }

  // Charge un template
  async loadTemplate(templateId) {
    const templatePath = path.join(this.templatesDir, `${templateId}.json`);
    
    if (!(await fs.pathExists(templatePath))) {
      throw new Error(`Template ${templateId} non trouvé`);
    }
    
    return fs.readJson(templatePath);
  }

  // Génère un callbot complet
  async generateCallBot(templateId, customConfig = {}) {
    console.log(`\n🤖 Génération du callbot: ${templateId}`);
    
    // 1. Charger le template
    const template = await this.loadTemplate(templateId);
    console.log(`✅ Template chargé: ${template.metadata.name}`);
    
    // 2. Merger avec config custom
    const finalTemplate = this.mergeConfig(template, customConfig);
    
    // 3. Générer system prompt
    const systemPrompt = this.promptGenerator.generate(finalTemplate);
    console.log(`✅ System prompt généré (${systemPrompt.length} chars)`);
    
    // 4. Générer config Vapi
    const vapiConfig = this.promptGenerator.generateVapiConfig(finalTemplate, {
      apiKey: process.env.VAPI_API_KEY || '${VAPI_API_KEY}',
      openaiApiKey: process.env.OPENAI_API_KEY || '${OPENAI_API_KEY}'
    });
    console.log(`✅ Configuration Vapi générée`);
    
    // 5. Créer dossier de sortie
    const outputPath = path.join(this.outputDir, templateId);
    await fs.ensureDir(outputPath);
    
    // 6. Écrire les fichiers
    await this.writeGeneratedFiles(outputPath, {
      template: finalTemplate,
      systemPrompt,
      vapiConfig,
      templateId
    });
    
    console.log(`\n🚀 CallBot généré dans: ${outputPath}`);
    return outputPath;
  }

  // Merge template avec config custom
  mergeConfig(template, customConfig) {
    const merged = { ...template };
    
    // Merge bot config
    if (customConfig.bot) {
      merged.bot = { ...merged.bot, ...customConfig.bot };
    }
    
    // Merge services
    if (customConfig.services) {
      merged.services = customConfig.services;
    }
    
    // Merge required fields
    if (customConfig.required_fields) {
      merged.required_fields = customConfig.required_fields;
    }
    
    return merged;
  }

  // Écrit tous les fichiers générés
  async writeGeneratedFiles(outputPath, { template, systemPrompt, vapiConfig, templateId }) {
    // 1. Template final
    await fs.writeJson(path.join(outputPath, 'template.json'), template, { spaces: 2 });
    
    // 2. System prompt
    await fs.writeFile(path.join(outputPath, 'system-prompt.txt'), systemPrompt);
    
    // 3. Config Vapi
    await fs.writeJson(path.join(outputPath, 'vapi-config.json'), vapiConfig, { spaces: 2 });
    
    // 4. README avec instructions
    const readme = this.generateReadme(template, templateId);
    await fs.writeFile(path.join(outputPath, 'README.md'), readme);
    
    // 5. Script de test local
    const testScript = this.generateTestScript(template);
    await fs.writeFile(path.join(outputPath, 'test-flow.js'), testScript);
    
    // 6. Exemple d'intégration
    const htmlExample = this.generateHtmlExample(vapiConfig);
    await fs.writeFile(path.join(outputPath, 'example.html'), htmlExample);
  }

  // Génère README avec instructions
  generateReadme(template, templateId) {
    return `# CallBot ${template.metadata.name}

**Generated by:** CallBot Generator V2  
**Template:** ${templateId}  
**Version:** ${template.metadata.version}

## Description
${template.metadata.description}

## Bot Configuration
- **Nom:** ${template.bot.name}
- **Rôle:** ${template.bot.role}
- **Ton:** ${template.bot.tone}

## Services
${template.services.map(s => `- ${s.name}: ${s.price > 0 ? s.price + '€' : 'Gratuit'} (${s.duration}min)`).join('\n')}

## Flux conversationnel
${template.flow.steps.map((step, i) => `${i + 1}. ${step}`).join(' → ')}

## Champs collectés
${template.required_fields.map(f => `- ${f.name}: ${f.question}`).join('\n')}

Generated on ${new Date().toLocaleDateString('fr-FR')}`;
  }

  // Génère script de test du flow
  generateTestScript(template) {
    return `const FlowEngine = require('../core/flow-engine');
const template = require('./template.json');

console.log('🧪 Test du flow:', template.metadata.name);
const flow = new FlowEngine(template);
console.log('Steps:', template.flow.steps.join(' → '));
console.log('Services:', template.services.length);
console.log('Required fields:', template.required_fields.length);`;
  }

  // Génère exemple HTML d'intégration
  generateHtmlExample(vapiConfig) {
    return `<!DOCTYPE html>
<html>
<head>
    <title>CallBot ${vapiConfig.assistant.name}</title>
</head>
<body>
    <h1>🤖 CallBot ${vapiConfig.assistant.name}</h1>
    <p>Cliquez sur le bouton pour démarrer la conversation vocale.</p>
    
    <script>
        // Integration Vapi ici
        console.log('CallBot ready:', '${vapiConfig.assistant.name}');
    </script>
</body>
</html>`;
  }

  // Mode interactif
  async interactive() {
    console.log('\n🚀 CallBot Generator V2 - Mode Interactif\n');
    
    const templates = await this.listTemplates();
    
    const answers = await inquirer.prompt([
      {
        type: 'list',
        name: 'templateId',
        message: 'Choisissez un template:',
        choices: templates.map(t => ({
          name: `${t.name} - ${t.description}`,
          value: t.id
        }))
      },
      {
        type: 'input',
        name: 'botName',
        message: 'Nom du bot (ou Enter pour garder celui du template):',
        default: ''
      },
      {
        type: 'confirm',
        name: 'generateNow',
        message: 'Générer le callbot maintenant ?',
        default: true
      }
    ]);
    
    if (answers.generateNow) {
      const customConfig = {};
      
      if (answers.botName) {
        customConfig.bot = { name: answers.botName };
      }
      
      const outputPath = await this.generateCallBot(answers.templateId, customConfig);
      console.log(`\n✨ CallBot prêt ! Dossier: ${outputPath}`);
    }
  }
}

// CLI
async function main() {
  const generator = new CallBotGenerator();
  await generator.init();
  
  const args = process.argv.slice(2);
  
  if (args.includes('--list-templates')) {
    const templates = await generator.listTemplates();
    console.log('\n📋 Templates disponibles:\n');
    templates.forEach(t => {
      console.log(`• ${t.id} - ${t.name}`);
      console.log(`  ${t.description}\n`);
    });
    return;
  }
  
  const templateIndex = args.indexOf('--template');
  if (templateIndex !== -1 && args[templateIndex + 1]) {
    const templateId = args[templateIndex + 1];
    await generator.generateCallBot(templateId);
    return;
  }
  
  // Mode interactif par défaut
  await generator.interactive();
}

// Execute si lancé directement
if (require.main === module) {
  main().catch(console.error);
}

module.exports = CallBotGenerator;